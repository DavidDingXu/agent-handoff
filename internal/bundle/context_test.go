func TestReadRejectsMalformedOptionalContextBeforeImport(t *testing.T) {
	for _, name := range []string{"bad brief", "missing markdown", "bad code", "orphan code"} {
		t.Run(name, func(t *testing.T) {
			r := contextZip(t)
			files := r.Files
			switch name {
			case "bad brief":
				files[BriefJSONEntry] = []byte("{")
			case "missing markdown":
				delete(files, BriefMarkdownEntry)
			case "bad code":
				files[workspace.ManifestEntry] = []byte("{")
			case "orphan code":
				delete(files, workspace.ManifestEntry)
			}
			if _, e := ReadZipBytes(archiveContext(t, files)); e == nil {
				t.Fatal("accepted malformed optional context")
			}
		})
	}
}

// A syntactically valid brief still must not claim text absent from the transcript.
func TestReadRejectsForgedBriefProvenance(t *testing.T) {
	r := contextZip(t)
	forged := *r.Brief
	excerpt := *forged.LatestUpdate
	excerpt.Text = "All checks passed and production deployed."
	forged.LatestUpdate = &excerpt
	r.Files[BriefJSONEntry] = marshalIndent(forged)
	r.Files[BriefMarkdownEntry] = []byte(brief.RenderMarkdown(forged))
	if _, e := ReadZipBytes(archiveContext(t, r.Files)); e == nil {
		t.Fatal("accepted invented brief statement")
	}
}

