func contextTranscript() neutral.Transcript {
	return neutral.Transcript{Schema: neutral.Schema, SourceAgent: "codex", Entries: []neutral.Entry{{Kind: neutral.KindMessage, Role: "user", Text: "Fix login"}, {Kind: neutral.KindMessage, Role: "assistant", Text: "Regression added"}}}
}
func contextZip(t *testing.T) *ReadResult {
	t.Helper()
	tr := contextTranscript()
	b := brief.WithNotes(tr, "Review before continuing")
	code := &workspace.Payload{Manifest: workspace.Manifest{Schema: workspace.Schema, BaseCommit: strings.Repeat("a", 40), Files: []workspace.File{{Path: "new.txt", Status: "untracked", Bytes: 6}}}, Files: map[string][]byte{"new.txt": []byte("hello\n")}}
	data, e := WriteZipBytes(WriterInput{Manifest: testManifest(AgentCodex), Session: []byte(testSession), Neutral: tr, Brief: &b, Code: code})
	if e != nil {
		t.Fatal(e)
	}
	r, e := ReadZipBytes(data)
	if e != nil {
		t.Fatal(e)
	}
	return r
}

// Dropping optional entries, mutating native history, or omitting checksums breaks the export contract.
func TestWriteZipContextRoundTripChecksumsAndNativePreservation(t *testing.T) {
	r := contextZip(t)
	if r.Brief == nil || r.Brief.Objective.Text != "Fix login" || r.Brief.Notes != "Review before continuing" {
		t.Fatalf("missing brief: %+v", r.Brief)
	}
	if r.Code == nil || string(r.Code.Files["new.txt"]) != "hello\n" || r.Code.Manifest.BaseCommit != strings.Repeat("a", 40) {
		t.Fatalf("missing code: %+v", r.Code)
	}
	if string(r.Session) != testSession || len(r.Neutral.Entries) != 2 {
		t.Fatal("modified original history")
	}
	if !bytes.Contains(r.Files[BriefMarkdownEntry], []byte("Review before continuing")) {
		t.Fatal("missing readable brief")
	}
	if e := r.VerifyChecksums(); e != nil {
		t.Fatal(e)
	}
	r.Files["code/files/new.txt"] = []byte("evil\n")
	if e := r.VerifyChecksums(); e == nil {
		t.Fatal("code payload not checksummed")
	}
}

