func TestBriefRoundTripsWorstCaseJSONEscapingWithinTextLimits(t *testing.T) {
	tr := neutral.Transcript{Schema: neutral.Schema, SourceAgent: "codex", Entries: []neutral.Entry{
		{Kind: neutral.KindMessage, Role: "user", Text: strings.Repeat("<", 8192)},
		{Kind: neutral.KindMessage, Role: "user", Text: strings.Repeat("<", 8192)},
		{Kind: neutral.KindMessage, Role: "assistant", Text: strings.Repeat("<", 8192)},
	}}
	for i := 0; i < 6; i++ {
		tr.Entries = append(tr.Entries, neutral.Entry{Kind: neutral.KindTool, Tool: "test", Input: strings.Repeat("<", 4096), Output: strings.Repeat("<", 4096)})
	}
	b := brief.WithNotes(tr, strings.Repeat("<", 8192))
	data, e := WriteZipBytes(WriterInput{Manifest: testManifest(AgentCodex), Session: []byte(testSession), Neutral: tr, Brief: &b})
	if e != nil {
		t.Fatal(e)
	}
	if _, e := ReadZipBytes(data); e != nil {
		t.Fatal(e)
	}
}
